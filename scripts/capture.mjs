import { chromium, expect } from '@playwright/test';
import { existsSync, mkdirSync } from 'node:fs';

const chrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const baseUrl = process.env.PROTOTYPE_URL || 'http://localhost:4173';
const browser = await chromium.launch({ executablePath: existsSync(chrome) ? chrome : undefined, headless: true });
const errors = [];
mkdirSync('artifacts', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  const capture = async (name) => {
    await page.waitForFunction(() => document.getAnimations().every((animation) => animation.playState !== 'running'));
    await page.screenshot({ path: `artifacts/${name}.png`, animations: 'disabled' });
  };
  await page.goto(baseUrl, { waitUntil: 'networkidle' });
  await expect(page.getByRole('button', { name: 'STEP INSIDE' })).toBeInViewport();
  await capture('01-onboarding-welcome');
  await page.getByRole('button', { name: 'STEP INSIDE' }).click();
  await page.getByRole('radio', { name: "I'm a member", exact: true }).click();
  await page.getByRole('button', { name: 'Use demo member Alex' }).click();
  await capture('02-onboarding-member');
  await page.getByRole('button', { name: 'CONTINUE AS A MEMBER' }).click();
  await expect(page.getByRole('radio', { name: 'Feature Push Day' })).toHaveAttribute('aria-checked', 'true');
  await capture('03-onboarding-focus');
  await page.getByRole('button', { name: 'THAT’S MY FOCUS' }).click();
  await capture('04-onboarding-ready');
  await page.getByRole('button', { name: 'MAKE YOURSELF AT HOME' }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back, Alex' })).toBeVisible();
  await capture('13-personal-home');
  await page.getByRole('button', { name: 'View gym capacity demo information' }).click();
  await expect(page.getByText(/42% is an illustrative occupancy example/)).toBeVisible();
  await page.getByRole('button', { name: 'Close capacity preview' }).click();
  await page.getByRole('tab', { name: 'Membership tab' }).click();
  await expect(page.getByText('DEMO-1042', { exact: true })).toBeVisible();
  await capture('14-member-dashboard');
  await page.getByRole('button', { name: 'View example visit history' }).click();
  await expect(page.getByRole('button', { name: 'BACK TO MEMBERSHIP' })).toBeInViewport({ ratio: 1 });
  await capture('15-visit-history');
  await page.getByRole('button', { name: 'Close visit history' }).click();
  await page.getByRole('tab', { name: 'Train tab' }).click();
  await expect(page.getByRole('heading', { name: 'TRAIN HARDER' })).toBeVisible();
  await capture('04-training-home');
  await page.getByRole('button', { name: /^Open Push Day,/ }).click();
  await capture('05-push-day');
  await page.getByRole('button', { name: /^1\. Incline Chest Press,/ }).click();
  await capture('07-exercise-detail');
  await page.getByRole('button', { name: 'Back to Push Day' }).click();
  await page.getByRole('button', { name: 'Back to training' }).click();
  await page.getByRole('tab', { name: 'EXERCISE LIBRARY' }).click();
  await capture('06-exercise-library');
  await page.getByRole('textbox', { name: 'Search exercises' }).fill('incline');
  await expect(page.getByRole('button', { name: /^Open / })).toHaveCount(1);
  await page.getByRole('tab', { name: 'More tab' }).click();
  await capture('11-more');
  await page.goto(`${baseUrl}/train/exercise/incline-chest-press?workout=push`);
  await expect(page.getByRole('heading', { name: 'INCLINE CHEST PRESS' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'INCLINE CHEST PRESS' })).toBeVisible();
  await page.setViewportSize({ width: 320, height: 568 });
  await page.goto(`${baseUrl}/onboarding`);
  await expect(page.getByRole('button', { name: 'STEP INSIDE' })).toBeInViewport();
  await capture('12-compact-phone');
  await page.getByRole('button', { name: 'STEP INSIDE' }).click();
  await expect(page.getByRole('button', { name: 'CONTINUE AS A MEMBER' })).toBeInViewport();
  await page.getByRole('button', { name: 'CONTINUE AS A MEMBER' }).click();
  await page.getByRole('radio', { name: 'Feature Leg Day' }).click();
  await page.getByRole('button', { name: 'THAT’S MY FOCUS' }).click();
  await expect(page.getByRole('button', { name: 'MAKE YOURSELF AT HOME' })).toBeInViewport();
  expect(errors).toEqual([]);
  console.log('Production preview verified: member onboarding, personal Home, capacity demo, member dashboard, visit history, training, direct links and compact-phone actions. Zero browser errors. Screenshots: artifacts/');
} finally {
  await browser.close();
}
